import type { NearbyStationBenchmark } from '../site-feasibility/siteFeasibilityTypes';

/**
 * Turns a candidate site and the stations around it into a node-link diagram.
 *
 * WHAT THIS IS FOR
 *
 * A score of 70 on the map says nothing about what a site would be up against.
 * Measured on real circles, the model's and the criteria's top suggestions sit
 * among stations that already exist: a 3 km circle around Sudirman holds 75
 * built cells out of 136. A planner reading "70" cannot see that the nearest
 * competitor is 400 m away. This diagram is where that becomes obvious.
 *
 * WHAT IT DELIBERATELY LEAVES OUT
 *
 * NearbyStationBenchmark also carries averageDailySessions, monthlyRevenueIdr
 * and their trends. Those are generated by getMockNearbyStationPerformance, and
 * downstream of that every charging session in both staging and production is
 * simulation output. Putting them on a competitive diagram would present
 * invented demand as measured fact. Only distance, operator, power and
 * connectors come from the database, and only those are drawn.
 *
 * Pure on purpose: the layout is arithmetic, so it is testable without mounting
 * React Flow, which is web-only in this monorepo.
 */

export type GraphNode = {
  id: string;
  kind: 'site' | 'station';
  label: string;
  sublabel: string;
  x: number;
  y: number;
  /** How much of a threat this competitor is. Absent on the candidate itself. */
  pressure?: Pressure;
};

export type GraphEdge = {
  id: string;
  source: string;
  target: string;
  label: string;
  pressure: Pressure;
};

/** Competitive pressure, from distance alone. Named so the UI never invents a number. */
export type Pressure = 'high' | 'moderate' | 'low';

/**
 * Distance bands, in km.
 *
 * 1 km is walking distance and the same trip-generating catchment, so anything
 * inside it competes for the same driver. Past 3 km a driver choosing between
 * the two is making a detour, which is a different question.
 */
export const PRESSURE_NEAR_KM = 1;
export const PRESSURE_MID_KM = 3;

/** Layout radius in px for the outermost ring. */
const LAYOUT_RADIUS = 210;

/** How many competitors to draw. Past this the ring stops being readable. */
export const MAX_COMPETITORS = 10;

export function competitivePressure(distanceKm: number): Pressure {
  if (distanceKm <= PRESSURE_NEAR_KM) return 'high';
  if (distanceKm <= PRESSURE_MID_KM) return 'moderate';
  return 'low';
}

export function formatDistance(distanceKm: number): string {
  return distanceKm < 1
    ? `${Math.round(distanceKm * 1000)} m`
    : `${distanceKm.toFixed(1)} km`;
}

/** Power and connectors, when the database has them. Never a fabricated number. */
export function stationSublabel(station: NearbyStationBenchmark): string {
  const parts: string[] = [];
  if (station.operator) parts.push(station.operator);
  if (typeof station.powerKw === 'number' && station.powerKw > 0) {
    parts.push(`${Math.round(station.powerKw)} kW`);
  }
  if (typeof station.totalConnectors === 'number' && station.totalConnectors > 0) {
    parts.push(`${station.totalConnectors} connector${station.totalConnectors === 1 ? '' : 's'}`);
  }
  return parts.join(' · ');
}

/**
 * One-line verdict on the neighbourhood, for the panel above the diagram.
 *
 * Counts rather than an average distance: "three within 1 km" is a fact a
 * planner acts on, while "mean 2.4 km" hides whether that is one at 200 m and
 * one at 4.6 km.
 */
export function pressureSummary(stations: NearbyStationBenchmark[]): string {
  if (!stations.length) return 'No existing SPKLU nearby. This site would not be competing.';
  const near = stations.filter((s) => competitivePressure(s.distanceKm) === 'high').length;
  const nearest = Math.min(...stations.map((s) => s.distanceKm));
  if (!near) {
    return `${stations.length} SPKLU nearby, none within ${PRESSURE_NEAR_KM} km. `
      + `Closest is ${formatDistance(nearest)}.`;
  }
  return `${near} SPKLU within ${PRESSURE_NEAR_KM} km, competing for the same drivers. `
    + `Closest is ${formatDistance(nearest)}.`;
}

/**
 * Nodes for the candidate and its competitors, laid out as a ring.
 *
 * The ring radius tracks real distance rather than being uniform, so a station
 * 400 m away sits visibly closer to the centre than one 4 km away. It is scaled
 * against the furthest competitor drawn, which keeps the diagram legible while
 * preserving the ordering a planner cares about.
 */
export function buildGraph(
  site: { id: string; label: string; score: number },
  stations: NearbyStationBenchmark[]
): { nodes: GraphNode[]; edges: GraphEdge[] } {
  const drawn = [...stations]
    .sort((a, b) => a.distanceKm - b.distanceKm)
    .slice(0, MAX_COMPETITORS);

  const centre: GraphNode = {
    id: site.id,
    kind: 'site',
    label: site.label,
    sublabel: `Viability ${site.score}`,
    x: 0,
    y: 0
  };

  if (!drawn.length) return { nodes: [centre], edges: [] };

  const furthest = Math.max(...drawn.map((s) => s.distanceKm)) || 1;
  const nodes: GraphNode[] = [centre];
  const edges: GraphEdge[] = [];

  drawn.forEach((station, index) => {
    // Start at the top and go clockwise, so the nearest competitor is always in
    // the same place and two sites can be compared at a glance.
    const angle = (index / drawn.length) * 2 * Math.PI - Math.PI / 2;
    // A floor of 0.35 keeps the closest station off the centre node.
    const scale = 0.35 + 0.65 * (station.distanceKm / furthest);
    const pressure = competitivePressure(station.distanceKm);

    nodes.push({
      id: station.id,
      kind: 'station',
      label: station.name,
      sublabel: stationSublabel(station),
      x: Math.cos(angle) * LAYOUT_RADIUS * scale,
      y: Math.sin(angle) * LAYOUT_RADIUS * scale,
      pressure
    });
    edges.push({
      id: `${site.id}-${station.id}`,
      source: site.id,
      target: station.id,
      label: formatDistance(station.distanceKm),
      pressure
    });
  });

  return { nodes, edges };
}
