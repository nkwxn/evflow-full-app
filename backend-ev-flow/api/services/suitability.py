"""One number for "how suitable is this place", from the model and the network.

WHAT IT COMBINES, AND WHY IT IS A BLEND RATHER THAN A PRODUCT

The acceptance criterion asks for a heatmap that is machine-learned, banded red
to green, and green where the existing network is over-saturated. The obvious
shape is demand divided by competition:

    contested = utilisation_prediction / (1 + stations_within_2km)

That was built and measured on 2026-08-27 over all 27,219 scored cells, and it
does not work. The prediction spreads 1.85x between its 5th and 95th percentile;
the discount spreads 13.6x. Multiplied, the result ranks at Spearman +0.836
against the discount alone and **-0.036 against the prediction** -- the machine
learning contributes nothing, and the map is a competitor count wearing a label.

The cause is not scaling. rank(prediction) and rank(discount) correlate at
-0.53: operators already built where demand is, so the two terms cancel. No
exponent rescues it -- damping to 1/(1+n)^0.25 balances them only by making the
saturation penalty too weak to turn a crowded district green.

So the terms are ranked separately and blended with a weight that is written
down, the way services/site_scoring.py already handles four criteria. What each
side contributes is then a decision on record rather than an accident of units.

WHY 0.5, AND WHY THAT DOES NOT MEAN EQUAL INFLUENCE

Measured across weights, the property that decides it is the last column:

    w     rho(suit, U)   rho(suit, discount)   served->green   red with none nearby
    0.6         0.846                -0.022             44%                    96%
    0.5         0.629                 0.289             60%                   100%
    0.4         0.227                 0.680             89%                   100%

At 0.5 and below, **every cell in the top decile has no competitor within 2 km**.
That is what a shortlist has to guarantee: the recommendation never points at a
place already crowded. Below 0.5 the prediction stops contributing.

Equal weights do not give equal influence -- 0.629 against 0.289 -- because 67%
of unbuilt cells have stations_2km = 0, so the discount's rank is one large block
of ties, and a tied variable adds less variance to a sum. Stated here because the
asymmetry looks like a bug otherwise.

WHAT THE WHOLE GRID DOES, MEASURED 2026-08-27

    region bands                          red 2,725  yellow 7,923  green 16,571
    red cells with a station within 2 km   0 of 2,725
    cells with >=4 competitors             4,262 -- all green, no exceptions
    rho(suitability, discount)            +0.657
    rho(suitability, prediction)          +0.118

The acceptance criterion falls out structurally: a cell with four competitors
carries a discount of 0.2, which cannot reach the median however high its
prediction, so it is green without a rule saying so.

That last row looks like the model is decorative and is not. 17,594 cells (65%)
have nothing inside 2 km, so their discount is tied at exactly 1.0 and the only
thing left to order them by is the prediction: **inside that block the rank
correlation with the prediction is +1.000**, and all 2,725 red cells come from
it. Among contested cells it is +0.840. The +0.118 is what comparing across two
anti-correlated blocks does to a single global coefficient, not a statement
about either block.

So: the supply term decides which BAND a cell lands in, the model decides the
ORDER within it, and the shortlist is model-ranked end to end. That is the
sentence to use; "generated by a machine-learning algorithm" on its own invites
the reader to assume the model chose the bands too.

WHAT THE NUMBER IS NOT

A forecast. The prediction underneath is trained on simulated sessions and
recovers an assumption about demand rather than measuring it, and the discount
counts stations rather than connectors, so ten single-connector sites and one
ten-connector site look identical to it. Say SCENARIO wherever it surfaces.
"""
from __future__ import annotations

import bisect
from dataclasses import dataclass
from typing import Any, Callable, Dict, List, Optional, Sequence, Tuple

#: The radius stations_2km is already defined over, in scripts/load_planning_cells.
#: Inherited rather than chosen: introducing a second radius here would create two
#: definitions of "nearby" that could drift apart.
SUPPLY_RADIUS_M = 2000.0

#: How much of the blend is the model. See the module docstring for the
#: measurement that chose it.
MODEL_WEIGHT = 0.5

#: Band floors as quantiles of the regional distribution. p90 is not a new
#: number: candidate_sites already gates its shortlist on the top decile, so the
#: product has committed to "top 10% is the shortlist" elsewhere. The median
#: describes itself. Both are named statistics rather than tuned constants, and
#: both are evaluated against whatever model is loaded, the way
#: services/resemblance_scale derives its ceiling.
RED_QUANTILE = 0.90
YELLOW_QUANTILE = 0.50

#: Resolution of the stored distributions. 1,001 points is 0.1% of a percentile,
#: far finer than three bands or a 0-100 display can show, and 8 KB instead of
#: the ~1 MB the raw values would cost.
QUANTILE_POINTS = 1001

Band = str  # "red" | "yellow" | "green"

_cache: Dict[Tuple[str, str], "RegionalScale"] = {}


@dataclass(frozen=True)
class Supply:
    """Existing competition for one cell's catchment."""
    stations_2km: int
    nearest_station_m: Optional[float]
    effective: float   # stations_2km + the sub-2km fraction
    discount: float    # 1 / (1 + effective)


def supply_discount(stations_2km: int, nearest_station_m: Optional[float],
                    radius_m: float = SUPPLY_RADIUS_M) -> Supply:
    """Turn the two supply columns into one number.

    stations_2km is the criterion's literal "over-saturation of existing network
    infrastructure", but it is a step function: a station 100 m away and one
    1,900 m away count the same. nearest_station_m is continuous but blind to
    how many, so three kilometres from ten stations beats 500 m from one. The
    fraction below folds the sub-2 km geometry back in as part of a station.

    A station at 0 m therefore contributes 1 + 1 = 2 and one at 1,999 m
    contributes 1 + 0.0005. The double count is deliberate: a charger in the same
    car park competes harder than one at the edge of the catchment.

    nearest_station_m is NULL only when no station exists to measure from, which
    is maximally unserved. Coalescing it to zero would say "a station is exactly
    here" and invert the term for every such cell -- the mistake that sat in
    planner_repo's coverage rank until it was found.
    """
    if nearest_station_m is None:
        near = 0.0
    else:
        near = max(0.0, min(1.0, (radius_m - min(float(nearest_station_m), radius_m)) / radius_m))
    effective = float(stations_2km) + near
    return Supply(int(stations_2km), nearest_station_m, effective, 1.0 / (1.0 + effective))


@dataclass(frozen=True)
class RegionalScale:
    """The distribution one cell is read against.

    Always the whole filtered region, never a viewport or a circle. Ranking
    inside a circle makes the best cell of a quiet suburb equal to the best cell
    of Sudirman -- the invariant candidate_sites_in_radius spends thirty lines
    defending.
    """
    trained_at: str
    supply_fingerprint: str
    cells_scored: int
    model_weight: float
    utilisation_q: Tuple[float, ...]
    discount_q: Tuple[float, ...]
    suitability_q: Tuple[float, ...]

    @property
    def red_floor(self) -> float:
        return self.suitability_q[int(RED_QUANTILE * (QUANTILE_POINTS - 1))]

    @property
    def yellow_floor(self) -> float:
        return self.suitability_q[int(YELLOW_QUANTILE * (QUANTILE_POINTS - 1))]

    def quantile_at(self, q: float) -> float:
        """The regional suitability at quantile `q`, 0..1.

        The same lookup red_floor and yellow_floor do, exposed because the
        shortlist gates on a caller-supplied quantile. Read from the stored
        table rather than recomputed, so a shortlist cutoff and a band edge can
        never come from two different passes over the region.
        """
        if not 0.0 <= q <= 1.0:
            raise ValueError(f"quantile must be within 0..1, got {q}")
        return self.suitability_q[int(q * (QUANTILE_POINTS - 1))]


def _quantiles(values: Sequence[float]) -> Tuple[float, ...]:
    ordered = sorted(values)
    n = len(ordered)
    return tuple(ordered[min(n - 1, int(round(i * (n - 1) / (QUANTILE_POINTS - 1))))]
                 for i in range(QUANTILE_POINTS))


def _pct_rank(value: float, quantiles: Tuple[float, ...]) -> float:
    """Where `value` falls in a distribution, 0..1."""
    return bisect.bisect_right(quantiles, value) / len(quantiles)


def build_scale(trained_at: str, supply_fingerprint: str, rows: Sequence[Dict[str, Any]],
                predict: Callable[[Sequence[Dict[str, Any]]], List[float]],
                location_features: Sequence[str],
                model_weight: float = MODEL_WEIGHT) -> RegionalScale:
    """Score the region once, and keep the shape of the result.

    `rows` must carry the model's location features plus stations_2km and
    nearest_station_m. Built cells are included: they are part of the region a
    cell is compared against, even though nothing recommends them.
    """
    if not rows:
        raise ValueError("no cells to build a suitability scale from")

    wanted = set(location_features)
    u = predict([{k: v for k, v in r.items() if k in wanted} for r in rows])
    d = [supply_discount(r.get("stations_2km") or 0, r.get("nearest_station_m")).discount
         for r in rows]
    uq, dq = _quantiles(u), _quantiles(d)
    suit = [model_weight * _pct_rank(a, uq) + (1 - model_weight) * _pct_rank(b, dq)
            for a, b in zip(u, d)]
    return RegionalScale(trained_at=trained_at, supply_fingerprint=supply_fingerprint,
                         cells_scored=len(rows), model_weight=model_weight,
                         utilisation_q=uq, discount_q=dq, suitability_q=_quantiles(suit))


def cached_scale(trained_at: str, supply_fingerprint: str,
                 load: Callable[[], Sequence[Dict[str, Any]]],
                 predict: Callable[[Sequence[Dict[str, Any]]], List[float]],
                 location_features: Sequence[str]) -> RegionalScale:
    """One scale per (model, supply state).

    The supply half of the key is what services/resemblance_scale could not
    afford: detecting a feature reload there would have cost a whole-grid pass on
    every request. Here supply is half the formula and the probe is two counts,
    so a station import invalidates the scale instead of silently ageing it.
    """
    key = (trained_at, supply_fingerprint)
    if key not in _cache:
        _cache[key] = build_scale(trained_at, supply_fingerprint, load(), predict,
                                  location_features)
    return _cache[key]


def reset_cache() -> None:
    """For tests, and after a retrain."""
    _cache.clear()


@dataclass(frozen=True)
class Suitability:
    utilisation: float
    supply: Supply
    suitability: float
    band: Band


def score(utilisation: float, stations_2km: int, nearest_station_m: Optional[float],
          scale: RegionalScale) -> Suitability:
    """One cell, read against the region."""
    s = supply_discount(stations_2km, nearest_station_m)
    value = (scale.model_weight * _pct_rank(utilisation, scale.utilisation_q)
             + (1 - scale.model_weight) * _pct_rank(s.discount, scale.discount_q))
    return Suitability(utilisation=utilisation, supply=s, suitability=value,
                       band=band(value, scale))


def band(value: float, scale: RegionalScale) -> Band:
    if value >= scale.red_floor:
        return "red"
    if value >= scale.yellow_floor:
        return "yellow"
    return "green"
